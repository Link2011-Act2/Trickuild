package dev.trickuild.gradle

import javax.lang.model.SourceVersion

internal object JavaMetadataWriter {
    fun validateNames(packageName: String, className: String) {
        require(SourceVersion.isName(packageName)) { "metadataPackage must be a valid Java package: '$packageName'" }
        require(SourceVersion.isIdentifier(className) && !SourceVersion.isKeyword(className)) {
            "metadataClassName must be a valid Java class name: '$className'"
        }
    }

    fun literal(value: String): String = buildString {
        append('"')
        value.forEach { char ->
            append(when (char) {
                '\\' -> "\\\\"
                '"' -> "\\\""
                '\n' -> "\\n"
                '\r' -> "\\r"
                '\t' -> "\\t"
                else -> if (char.isISOControl()) "\\u%04x".format(char.code) else char.toString()
            })
        }
        append('"')
    }

    fun render(packageName: String, className: String, fields: Map<String, Any>, buildInstant: String?): String {
        validateNames(packageName, className)
        return buildString {
            appendLine("package $packageName;")
            appendLine()
            appendLine("// Generated by Trickuild. Do not edit.")
            if (buildInstant != null) appendLine("// Build execution: $buildInstant")
            appendLine("public final class $className {")
            appendLine("    private $className() {}")
            fields.forEach { (name, value) ->
                val type = if (value is Int) "int" else "String"
                val literal = if (value is Int) value.toString() else literal(value.toString())
                appendLine("    public static final $type $name = $literal;")
            }
            appendLine("}")
        }
    }
}
